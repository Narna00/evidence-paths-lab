from pathlib import Path
import hashlib
import json
import platform
import statistics
import sys
import zipfile
from reportlab.graphics.shapes import Drawing,String,Rect
from reportlab.graphics.charts.lineplots import LinePlot
from reportlab.graphics import renderSVG
from reportlab.lib.colors import HexColor,Color

root=Path(__file__).resolve().parent
folder=root/'pilot-results'
rows=[json.loads(line) for line in (folder/'raw.jsonl').read_text().splitlines()]
summary=json.loads((folder/'summary.json').read_text())
methods=['optimistic','two_origins','bounds_random','bounds_path_first','bounds_gain']
text='''# Exploratory synthetic pilot results

Generated by the included benchmark, not invented observations. This pilot is exploratory and uses a perfect unit-cost validation oracle with sparse correct initial trusted evidence. It does not evaluate live assessment efficacy.

120 candidate graphs; four topology families; 30 seeds per family; five methods; budgets 0/2/5/10; 2,400 raw method rows. The two observation-only baselines perform no validation regardless of the displayed budget. Planning methods can stop before reaching the budget.

## Budget 5: all-family descriptive aggregate

This aggregate is shown for orientation. Per-family results and paired intervals are in the raw summary; the rows are not independent across budgets/methods.

| Method | False-safe rate | False-confirmed rate | Resolved coverage | Mean declared loss | Mean validations used |
|---|---:|---:|---:|---:|---:|
'''
for method in methods:
    selected=[row for row in rows if row['method']==method and row['budget']==5]
    values={metric:statistics.mean(row[metric] for row in selected) for metric in ('false_safe','false_alarm','covered','loss','validations_used')}
    text+=f'| {method} | {values["false_safe"]:.4f} | {values["false_alarm"]:.4f} | {values["covered"]:.4f} | {values["loss"]:.4f} | {values["validations_used"]:.4f} |\n'
text+='''
## Interpretation

The proposed bounds_gain heuristic did **not** outperform the stronger path-first baseline on this aggregate: coverage was 0.75 versus 0.80 at budget 5, and declared loss was 0.25 versus 0.20. It used slightly fewer validations on average, which is a tradeoff rather than demonstrated superiority. Preserve this negative finding. None of the four per-family budget-5 comparisons establishes a clear advantage over path-first under the pointwise intervals below.

All bounds methods produced zero false-safe and false-confirmed decisions under the pilot's correctness assumptions. That is expected from the containment model and perfect validation, not empirical evidence of robustness to incorrect trusted validators or omitted true transitions. Observation-only methods often treated missing transitions as absent and therefore made false-safe decisions in this synthetic setup. Their lower information/cost budget makes them contextual baselines, not fair competitors to a validation planner.

## Budget 5: paired loss differences by family

Difference is bounds_gain minus baseline; negative favors bounds_gain. Intervals are pointwise 95% paired percentile bootstrap over 30 seeds with 1,000 resamples. No multiplicity adjustment or confirmatory significance claim.

| Family | Baseline | Mean paired loss difference | Pointwise interval |
|---|---|---:|---|
'''
for item in summary['paired_loss_contrasts']:
    if item['budget']!=5:continue
    low,high=item['ci95_percentile']
    text+=f'| {item["family"]} | {item["contrast"].split(" minus ")[1].replace(" loss","")} | {item["mean"]:.4f} | [{low:.4f}, {high:.4f}] |\n'
text+='''
## What to do next

Use path-first as a serious baseline. Investigate graph families where the heuristic wastes effort, add actual validation costs and imperfect outcomes, compare to exact small-instance planning, and separate exploratory tuning from a frozen held-out evaluation. Do not rename the baseline, remove difficult seeds, or select a favorable budget to create a superiority claim.

See PROTOCOL.md for the full caveats and MODEL.md for the conditional guarantee. Raw graph fixtures, truth labels, rows, summaries, and integrity hashes are in pilot-results.zip. Runtime is a local measurement and changes across runs; semantic outcomes should reproduce from the same code/seeds.

![Per-family coverage curves](pilot-coverage.png)
'''
(root/'PILOT.md').write_text(text,encoding='utf-8')
figure=Drawing(1000,720)
figure.add(Rect(0,0,1000,720,fillColor=HexColor('#ffffff'),strokeColor=None))
figure.add(String(500,690,'Synthetic pilot: resolved query coverage',fontName='Helvetica-Bold',fontSize=20,textAnchor='middle'))
figure.add(String(500,665,'Perfect validation oracle; 30 seeds per family; descriptive curves',fontSize=12,textAnchor='middle'))
styles={'bounds_random':('#637a91','Random unknown edge'),'bounds_path_first':('#d88b17','Path-first'),'bounds_gain':('#2164b0','Branch/corridor heuristic')}
for panel,family in enumerate(['layered','cyclic','bottleneck','heldout_random']):
    x=75+(panel%2)*480;y=390-(panel//2)*300
    plot=LinePlot();plot.x=x;plot.y=y;plot.width=400;plot.height=210;plot.data=[]
    all_points=[]
    for method,(color,label) in styles.items():
        points=sorted((item['budget'],item['covered']) for item in summary['groups'] if item['family']==family and item['method']==method)
        all_points.append(points)
    plot.data=all_points
    plot.xValueAxis.valueMin=0;plot.xValueAxis.valueMax=10;plot.xValueAxis.valueSteps=[0,2,5,10]
    plot.yValueAxis.valueMin=0;plot.yValueAxis.valueMax=1;plot.yValueAxis.valueSteps=[0,.25,.5,.75,1]
    plot.yValueAxis.visibleGrid=True;plot.yValueAxis.gridStrokeColor=HexColor('#e0e6ec')
    for index,(method,(color,label)) in enumerate(styles.items()):
        plot.lines[index].strokeColor=HexColor(color);plot.lines[index].strokeWidth=2
    figure.add(plot)
    figure.add(String(x+200,y+230,family.replace('_',' ').title(),fontName='Helvetica-Bold',fontSize=14,textAnchor='middle'))
    figure.add(String(x+200,y-35,'Maximum validation budget',fontSize=11,textAnchor='middle'))
figure.add(String(18,350,'Resolved fraction',fontSize=11,angle=90))
for index,(method,(color,label)) in enumerate(styles.items()):
    figure.add(String(180+index*300,20,label,fillColor=HexColor(color),fontSize=12,textAnchor='middle'))
renderSVG.drawToFile(figure,str(root/'pilot-coverage.svg'))
# Rasterization is performed by the bundled SVG renderer after this script.
ledger={'python':sys.version,'platform':platform.platform(),'invocation':'python benchmark.py --seeds 30 --output pilot-results',
        'source_sha256':{name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in ('evidence_paths.py','benchmark.py','test_evidence_paths.py')},
        'regression_tests':12,'status':'exploratory; not preregistered; synthetic only'}
(folder/'environment.json').write_text(json.dumps(ledger,indent=2)+'\n',encoding='utf-8')
manifest=json.loads((folder/'manifest.json').read_text())
manifest['files']['environment.json']=hashlib.sha256((folder/'environment.json').read_bytes()).hexdigest()
(folder/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
with zipfile.ZipFile(root/'pilot-results.zip','w',zipfile.ZIP_DEFLATED) as bundle:
    for path in sorted(folder.iterdir()):bundle.write(path,path.name)
print('Pilot report, two plot formats, environment ledger, and complete raw-results archive created')
